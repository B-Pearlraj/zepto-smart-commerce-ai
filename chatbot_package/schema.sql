-- ======================================================================
-- Zepto Smart Commerce AI  -  Document Chatbot schema (Neon / PostgreSQL)
--
-- Adds three NEW chatbot tables, plus `prediction_audit` (section 0).
-- `prediction_audit` already exists in your code (database_schema.py) but
-- was never created in Neon, which made /health return 503.
-- Everything is IF NOT EXISTS, so nothing existing is changed or lost.
--
-- How to run (pick one):
--   1. Neon console -> SQL Editor -> paste this whole file -> Run
--   2. Do nothing: the FastAPI app runs this file automatically on
--      startup (chatbot_repository.ensure_chatbot_tables)
--
-- Every statement is idempotent (IF NOT EXISTS), so re-running is safe.
-- ======================================================================


-- ----------------------------------------------------------------------
-- 0. prediction_audit  (same definition as database_schema.py)
--    Needed by /health, /predict and /predictions/recent.
-- ----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS prediction_audit (
    id                           BIGSERIAL PRIMARY KEY,
    request_timestamp            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    model_version                VARCHAR(50) NOT NULL,
    delivery_charge              DOUBLE PRECISION NOT NULL,
    delivery_time_minutes        DOUBLE PRECISION NOT NULL,
    rider_acceptance_probability DOUBLE PRECISION NOT NULL,
    rider_acceptance             SMALLINT NOT NULL CHECK (rider_acceptance IN (0, 1)),
    weather_source               VARCHAR(100),
    traffic_source               VARCHAR(100),
    created_at                   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_prediction_audit_request_timestamp
    ON prediction_audit (request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_prediction_audit_model_version
    ON prediction_audit (model_version);

CREATE INDEX IF NOT EXISTS idx_prediction_audit_created_at
    ON prediction_audit (created_at DESC);


-- ----------------------------------------------------------------------
-- 1. Documents uploaded by the admin
--    Only the extracted text is stored (not the original file), which
--    keeps the Neon storage footprint small.
-- ----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS chatbot_documents (
    id               BIGSERIAL PRIMARY KEY,
    title            VARCHAR(200) NOT NULL,
    filename         VARCHAR(255),
    content_type     VARCHAR(100),
    file_size_bytes  BIGINT,
    char_count       INTEGER      NOT NULL DEFAULT 0,
    chunk_count      INTEGER      NOT NULL DEFAULT 0,

    -- Admin can switch a document off without deleting it.
    is_active        BOOLEAN      NOT NULL DEFAULT TRUE,

    -- SHA-256 of the extracted text: blocks accidental duplicate uploads.
    content_hash     CHAR(64)     NOT NULL UNIQUE,

    created_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_chatbot_documents_created_at
    ON chatbot_documents (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_chatbot_documents_is_active
    ON chatbot_documents (is_active);


-- ----------------------------------------------------------------------
-- 2. Searchable chunks of each document
--    `search_vector` is generated by PostgreSQL itself, so it can never
--    get out of sync with `content`.
-- ----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS chatbot_chunks (
    id             BIGSERIAL PRIMARY KEY,
    document_id    BIGINT   NOT NULL
                   REFERENCES chatbot_documents (id) ON DELETE CASCADE,
    chunk_index    INTEGER  NOT NULL,
    content        TEXT     NOT NULL,
    search_vector  TSVECTOR
                   GENERATED ALWAYS AS (to_tsvector('english', content)) STORED,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (document_id, chunk_index)
);

CREATE INDEX IF NOT EXISTS idx_chatbot_chunks_search_vector
    ON chatbot_chunks USING GIN (search_vector);

CREATE INDEX IF NOT EXISTS idx_chatbot_chunks_document_id
    ON chatbot_chunks (document_id);


-- ----------------------------------------------------------------------
-- 3. Conversation log
--    Lets the admin see which questions the documents could NOT answer,
--    so they know what to upload next.
-- ----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS chatbot_messages (
    id                BIGSERIAL PRIMARY KEY,
    session_id        VARCHAR(64),
    question          TEXT        NOT NULL,
    answer            TEXT        NOT NULL,
    matched           BOOLEAN     NOT NULL DEFAULT FALSE,
    top_document_id   BIGINT
                      REFERENCES chatbot_documents (id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_chatbot_messages_created_at
    ON chatbot_messages (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_chatbot_messages_matched
    ON chatbot_messages (matched);
